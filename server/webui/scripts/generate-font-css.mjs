/** Maintenance only: sources.json owns the local face inventory, not UI options.
 * Run after verified asset/provenance changes. Never downloads fonts. */
import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';

const records = JSON.parse(readFileSync(new URL('../static/fonts/sources.json', import.meta.url)));
const css = records
	.map(
		(face) => `@font-face {
	font-family: '${face.cssFamily}';
	font-style: ${face.style};
	font-weight: ${face.weight};
	font-display: swap;
	src: url('/fonts/${face.file}') format('woff2');
	unicode-range: ${face.unicodeRange};
}`
	)
	.join('\n');
const target = new URL('../src/lib/styles/local-fonts.css', import.meta.url);
writeFileSync(
	target,
	await format(
		'/* Generated by scripts/generate-font-css.mjs from static/fonts/sources.json. */\n' +
			css +
			'\n',
		{ ...(await resolveConfig(target)), filepath: target.pathname }
	)
);
